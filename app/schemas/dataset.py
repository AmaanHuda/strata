"""Dataset registry schemas."""
from datetime import datetime
from typing import Any, Dict, List, Optional
from uuid import UUID
from pydantic import BaseModel, ConfigDict, Field


class DatasetRegisterRequest(BaseModel):
    name: str = Field(..., min_length=2, max_length=255)
    version: str = "1.0.0"
    source: Optional[str] = None
    authority: Optional[str] = None
    license: Optional[str] = "Gov-Open"
    acquisition_date: Optional[str] = None
    modality: str = Field(..., description="satellite, lidar, dem, dsm, drone, cadastral_vector, osm")
    crs: str = "EPSG:4326"
    resolution_m: Optional[str] = None
    coverage_area: Optional[str] = None
    record_count: Optional[str] = None
    manifest: Optional[Dict[str, Any]] = None
    metadata_: Optional[Dict[str, Any]] = Field(None, alias="metadata")


class DatasetOut(BaseModel):
    model_config = ConfigDict(from_attributes=True, populate_by_name=True)
    id: UUID
    name: str
    version: str
    source: Optional[str] = None
    authority: Optional[str] = None
    license: Optional[str] = None
    acquisition_date: Optional[datetime] = None
    validation_status: Optional[str] = None
    modality: Optional[str] = None
    crs: Optional[str] = None
    resolution_m: Optional[str] = None
    coverage_area: Optional[str] = None
    record_count: Optional[str] = None
    is_active: bool
    ingested_at: datetime


# --- GeoJSON building import (dataset ingestion contract) ---


class BuildingImportError(BaseModel):
    """A single feature that could not be imported, with the reason why."""
    index: int
    reason: str


class BuildingImportResult(BaseModel):
    """Outcome of a GeoJSON building-footprint import."""
    filename: Optional[str] = None
    features_received: int
    buildings_imported: int
    buildings_skipped: int
    parcels_created: int
    parcels_reused: int
    ulpins_generated: int
    imported_building_ids: List[UUID] = Field(default_factory=list)
    errors: List[BuildingImportError] = Field(default_factory=list)
    model_version: str
    district: str
    state: str
    # Candidate ULPINs generated by this path are NON-AUTHORITATIVE by design.
    authoritative: bool = False


class ImportStatusOut(BaseModel):
    """Current ingest state so the frontend can prove the DB is no longer empty."""
    total_buildings: int
    active_buildings: int
    total_parcels: int
    buildings_with_geometry: int
    buildings_with_candidate_ulpin: int
